const AUDIT_SECRET_KEY = /(token|secret|password|private.?key|service.?role|connection.?string|mongodb|redis|supabase|firebase|cloudflare|authorization|cookie)/i;
const DISCORD_TOKEN_PATTERN = /^[A-Za-z0-9_-]{24,}\.[A-Za-z0-9_-]{6}\./;

export type GuildAuthorizationDecision = 'full' | 'temp' | 'deny';

/** Parse only authorization buttons generated by the private review workflow. */
export function parseGuildAuthorizationButton(customId: string): {
  decision: GuildAuthorizationDecision;
  guildId: string;
} | null {
  const match = /^guild-auth:(full|temp|deny):(\d{17,20})$/.exec(customId);
  if (!match) return null;
  const decision = match[1];
  const guildId = match[2];
  if (!decision || !guildId) return null;
  return { decision: decision as GuildAuthorizationDecision, guildId };
}

export function redactAuditMeta(value: Record<string, unknown>): Record<string, unknown> {
  const walk = (input: unknown, depth: number): unknown => {
    if (depth > 4) return '[truncated]';
    if (typeof input === 'string') {
      if (
        /^(?:mongodb(?:\+srv)?|postgres(?:ql)?|redis):\/\//i.test(input) ||
        DISCORD_TOKEN_PATTERN.test(input) ||
        /-----BEGIN .*PRIVATE KEY-----/.test(input)
      ) return '[redacted]';
      return input.slice(0, 512);
    }
    if (Array.isArray(input)) return input.slice(0, 25).map((item) => walk(item, depth + 1));
    if (input && typeof input === 'object') {
      const output: Record<string, unknown> = {};
      for (const [key, child] of Object.entries(input as Record<string, unknown>).slice(0, 50)) {
        output[key] = AUDIT_SECRET_KEY.test(key) ? '[redacted]' : walk(child, depth + 1);
      }
      return output;
    }
    return input;
  };
  const redacted = walk(value, 0) as Record<string, unknown>;
  try {
    if (Buffer.byteLength(JSON.stringify(redacted), 'utf8') > 8 * 1024) return { notice: 'audit metadata truncated' };
  } catch {
    return { notice: 'audit metadata unavailable' };
  }
  return redacted;
}

